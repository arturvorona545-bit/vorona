# Создайте дочерний класс с собственным атрибутом:
# 1. Создайте класс `Fish`, который наследуется от `Animal`
# 2. Добавьте конструктор `__init__` с параметром `name`
# 3. Внутри конструктора вызовите конструктор родителя для `name`
# 4. Добавьте атрибут `water_type` со значением "морская" прямо в классе (общий атрибут)
# 5. Добавьте метод `swim`, который выводит: "[name] плавает в [water_type] воде"
# 6. Создайте объект класса `Fish` с именем "Немо"
# 7. Вызовите метод `swim`

class Fish(Animal):
    water_type = "морская"
    def __init__(self, name):
        super().__init__(name)
    def swim(self):
        print(f"{self.name} плавает в {self.water_type} воде")
my_fish = Fish("Немо")
my_fish.swim()


# Задача №6 (Тема: Наследование с добавлением методов)
# Создайте цепочку наследования:
# 1. Создайте класс `Vehicle` (транспортное средство)
# 2. Добавьте конструктор `__init__` с параметром `brand`
# 3. Сохраните `brand` как атрибут экземпляра
# 4. Добавьте метод `honk`, который выводит: "[brand] сигналит: Бип!"
# 5. Создайте класс `Car`, наследующий от `Vehicle`
# 6. Добавьте в `Car` метод `drive`, который выводит: "[brand] едет"
# 7. Создайте объект класса `Car` с брендом "Toyota"
# 8. Вызовите оба метода: `honk` (унаследованный) и `drive` (собственный)

class Vehicle():
    def __init__(self, brand):
        self.brand = brand
    def honk(self):
        print(f"{self.brand} сигналит: Бип!")
class Car(Vehicle):
    def drive(self):
        print(f"{self.brand} едет")
my_car = Car("Toyota")
my_car.honk()
my_car.drive()



