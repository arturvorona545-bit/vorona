# Задача №1 (Тема: Создание родительского класса)
# Создайте простой родительский класс:
# 1. Создайте класс `Animal`
# 2. Добавьте конструктор `__init__` с параметром `name`
# 3. Сохраните `name` как атрибут экземпляра
# 4. Добавьте метод `eat`, который выводит: "[name] ест"

class Animal:
    def __init__(self, name):
        self.name = name

    def eat(self):
        print(f"{self.name} ест")

