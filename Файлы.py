# Задача №5 (Тема: Работа с файлами - построчное чтение)
# Напишите программу, которая читает файл test.txt построчно:
# 1. Используя with, откройте файл "test.txt" в режиме чтения ('r')
# 2. Используйте цикл for для чтения файла построчно
# 3. Для каждой строки выводите: "Строка [номер]: [содержимое строки]"
# 4. Используйте enumerate() для нумерации строк (начиная с 1)
# 5. Выведите сообщение: "Построчное чтение завершено"

with open("test.txt", "r", encoding="utf-8") as file:
    for i, line in enumerate(file, start=1):
        cleaned_line = line.strip()
        print(f"Строка {i}: {cleaned_line}")
print("Построчное чтение завершено")

