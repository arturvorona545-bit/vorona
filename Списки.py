# Задача №10 (по спискам, из раздела: Слияние списков)
# У вас есть два списка:
# list_a = ["a", "b", "c"]
# list_b = ["d", "e", "f"]
# Напишите код, который:
# 1. Создаст новый список `combined` путем сложения (`+`) списка `list_a` и списка `list_b`.
# 2. Добавит все элементы из списка `list_b` в конец списка `list_a` с помощью метода.
