# Задача №5 (Тема: Декораторы)
# Напишите простой декоратор:
# 1. Создайте декоратор с именем `simple_decorator`
# 2. Декоратор должен добавлять строку "Функция вызвана" перед вызовом функции
# 3. Создайте функцию `say_hello`, которая выводит "Привет!"
# 4. Примените декоратор к функции `say_hello`
# 5. Вызовите функцию `say_hello`

def simple_decorator(func):
    def wrapper() :
        print("Функция вызвана")
        func()
    return wrapper
def say_hello():
    print("Привет!")
say_hello = simple_decorator(say_hello)
say_hello()


